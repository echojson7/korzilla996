/* Наличие по остатку: нет учёта, нет, мало, есть. */
export function availability(stock) {
  if (stock == null) return { key: "untracked", tone: "gray" };
  if (stock <= 0) return { key: "out", tone: "red" };
  if (stock <= LOW_STOCK) return { key: "low", tone: "amber" };
  return { key: "in", tone: "green" };
}

